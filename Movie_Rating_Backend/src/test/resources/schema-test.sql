-- H2 测试库建表脚本（MODE=MySQL; DATABASE_TO_LOWER=TRUE）
-- 镜像生产 schema.sql 的关键约束：主键 / UNIQUE(UserID,MovieID) / CHECK(Score 1~10) / 外键 ON DELETE CASCADE。
-- 刻意省略索引、ENGINE、CHARSET（与行为无关）；TEXT 改用 CLOB 以兼容 H2。

DROP TABLE IF EXISTS movie_actor1707;
DROP TABLE IF EXISTS movie_director1707;
DROP TABLE IF EXISTS comment1707;
DROP TABLE IF EXISTS rating1707;
DROP TABLE IF EXISTS movie1707;
DROP TABLE IF EXISTS actor1707;
DROP TABLE IF EXISTS director1707;
DROP TABLE IF EXISTS user1707;

CREATE TABLE user1707 (
  UserID INT AUTO_INCREMENT PRIMARY KEY,
  Username VARCHAR(50) NOT NULL UNIQUE,
  Password VARCHAR(100) NOT NULL,
  Email VARCHAR(100),
  RegisterTime DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE movie1707 (
  MovieID INT AUTO_INCREMENT PRIMARY KEY,
  Title VARCHAR(100) NOT NULL,
  ReleaseYear INT,
  Duration INT,
  Genre VARCHAR(50),
  Language VARCHAR(50),
  Country VARCHAR(50),
  Synopsis CLOB,
  Rating DECIMAL(3,1) DEFAULT 0.0,
  PosterUrl VARCHAR(255),
  JumpUrl VARCHAR(255)
);

CREATE TABLE actor1707 (
  ActorID INT AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(50),
  Gender VARCHAR(10),
  BirthDate DATE,
  Nationality VARCHAR(50),
  PhotoUrl VARCHAR(255),
  CONSTRAINT chk_actor_gender CHECK (Gender IN ('男', '女'))
);

CREATE TABLE director1707 (
  DirectorID INT AUTO_INCREMENT PRIMARY KEY,
  Name VARCHAR(50),
  Gender VARCHAR(10),
  BirthDate DATE,
  Nationality VARCHAR(50),
  CONSTRAINT chk_director_gender CHECK (Gender IN ('男', '女'))
);

CREATE TABLE comment1707 (
  CommentID INT AUTO_INCREMENT PRIMARY KEY,
  UserID INT,
  MovieID INT,
  Content CLOB NOT NULL,
  CommentTime DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_comment_user FOREIGN KEY (UserID) REFERENCES user1707 (UserID) ON DELETE CASCADE,
  CONSTRAINT fk_comment_movie FOREIGN KEY (MovieID) REFERENCES movie1707 (MovieID) ON DELETE CASCADE
);

CREATE TABLE rating1707 (
  RatingID INT AUTO_INCREMENT PRIMARY KEY,
  UserID INT,
  MovieID INT,
  Score INT,
  RatingTime DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_rating_user_movie UNIQUE (UserID, MovieID),
  CONSTRAINT chk_rating_score CHECK (Score BETWEEN 1 AND 10),
  CONSTRAINT fk_rating_user FOREIGN KEY (UserID) REFERENCES user1707 (UserID) ON DELETE CASCADE,
  CONSTRAINT fk_rating_movie FOREIGN KEY (MovieID) REFERENCES movie1707 (MovieID) ON DELETE CASCADE
);

CREATE TABLE movie_actor1707 (
  MovieID INT NOT NULL,
  ActorID INT NOT NULL,
  RoleName VARCHAR(100),
  PRIMARY KEY (MovieID, ActorID),
  CONSTRAINT fk_ma_movie FOREIGN KEY (MovieID) REFERENCES movie1707 (MovieID) ON DELETE CASCADE,
  CONSTRAINT fk_ma_actor FOREIGN KEY (ActorID) REFERENCES actor1707 (ActorID) ON DELETE CASCADE
);

CREATE TABLE movie_director1707 (
  MovieID INT NOT NULL,
  DirectorID INT NOT NULL,
  PRIMARY KEY (MovieID, DirectorID),
  CONSTRAINT fk_md_movie FOREIGN KEY (MovieID) REFERENCES movie1707 (MovieID) ON DELETE CASCADE,
  CONSTRAINT fk_md_director FOREIGN KEY (DirectorID) REFERENCES director1707 (DirectorID) ON DELETE CASCADE
);